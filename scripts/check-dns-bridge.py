"""Bounded offline native DNS integration check. Run AndroidDnsTest first to generate the adapter fixture.

No remote DNS/server: the queried name is a local Xray hosts entry. The only listener is loopback.
"""
import json, pathlib, socket, struct, subprocess, sys, time

root=pathlib.Path(__file__).resolve().parents[1]
binary=pathlib.Path(sys.argv[1]).resolve()
source=json.loads((root/'core/build/dns-bridge-fixture.json').read_text())
# Replace only the device's TUN ingress with the same-tag loopback test ingress.
with socket.socket() as port_socket:
    port_socket.bind(('127.0.0.1',0));port=port_socket.getsockname()[1]
source['inbounds']=[{'tag':source['inbounds'][0]['tag'],'listen':'127.0.0.1','port':port,'protocol':'dokodemo-door',
                     'settings':{'address':'172.19.0.2','port':53,'network':'tcp,udp'}}]
source['log']={'loglevel':'warning'}
folder=root/'.gradle/upgrade-audit/dns-bridge';folder.mkdir(parents=True,exist_ok=True)
config=folder/'runtime.json';config.write_text(json.dumps(source))
subprocess.run([str(binary),'run','-test','-config',str(config)],check=True,capture_output=True)
query=struct.pack('!HHHHHH',0x5347,0x0100,1,0,0,0)+b''.join(bytes([len(s)])+s.encode() for s in 'health.signet.test'.split('.'))+b'\0'+struct.pack('!HH',1,1)
def validate(response):
    ident,flags,qd,answers,_,_=struct.unpack('!HHHHHH',response[:12])
    assert ident==0x5347 and flags&0x8000 and flags&15==0 and qd==1 and answers>=1
    # Local synthetic hosts response must be exactly the expected A address.
    assert b'\xc6\x12\x00\x01' in response
def receive(sock,count):
    result=b''
    while len(result)<count:
        block=sock.recv(count-len(result));assert block;result+=block
    return result
with (folder/'native.log').open('wb') as log:
    process=subprocess.Popen([str(binary),'run','-config',str(config)],stdout=log,stderr=subprocess.STDOUT)
    try:
        deadline=time.monotonic()+5
        while True:
            assert process.poll() is None,'Native core exited'
            try:
                probe=socket.create_connection(('127.0.0.1',port),timeout=.2);probe.close();break
            except OSError:
                if time.monotonic()>=deadline:raise
                time.sleep(.05)
        with socket.socket(socket.AF_INET,socket.SOCK_DGRAM) as udp:
            udp.settimeout(3);udp.sendto(query,('127.0.0.1',port));validate(udp.recv(4096))
        with socket.create_connection(('127.0.0.1',port),timeout=3) as tcp:
            tcp.sendall(struct.pack('!H',len(query))+query)
            size=struct.unpack('!H',receive(tcp,2))[0];validate(receive(tcp,size))
    finally:
        process.terminate()
        try:process.wait(timeout=5)
        except subprocess.TimeoutExpired:process.kill();process.wait()
result={'nativeCore':subprocess.check_output([str(binary),'version'],text=True).splitlines()[0],
        'udp':'PASS','tcp':'PASS','hostsAnswer':'198.18.0.1','dnsUpstream':'unreachable loopback; hosts resolves inside Xray',
        'fixture':'Generated by AndroidDnsTest from the production adapter',
        'scope':'loopback native DNS adapter; Android TUN/netd and physical phone not exercised'}
out=root/'tests/evidence/0.2.3';out.mkdir(parents=True,exist_ok=True)
(out/'dns-bridge.json').write_text(json.dumps(result,indent=2)+'\n')
print('Native DNS bridge UDP/TCP PASS')
