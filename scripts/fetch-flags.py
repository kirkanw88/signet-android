"""Render pinned MIT flag-icons SVGs into local Android PNG resources (no runtime network).
Requires Python Playwright and a local Chrome/Edge. Resources are committed, CI needn't render.
"""
import base64, hashlib, io, json, pathlib, urllib.request, zipfile
from playwright.sync_api import sync_playwright
root=pathlib.Path(__file__).resolve().parents[1]
commit='ac7e0eb3259eb62aa6100c435607e2fe03896a97'
url=f'https://codeload.github.com/lipis/flag-icons/zip/{commit}'
cache=root/'.gradle/upgrade-audit/flag-source.zip';cache.parent.mkdir(parents=True,exist_ok=True)
if not cache.exists():cache.write_bytes(urllib.request.urlopen(url,timeout=90).read())
raw=cache.read_bytes();records=[]
output=root/'app/src/main/res/drawable-nodpi';output.mkdir(exist_ok=True)
with zipfile.ZipFile(io.BytesIO(raw)) as archive,sync_playwright() as playwright:
    browser=None
    for channel in ('chrome','msedge'):
        try:browser=playwright.chromium.launch(channel=channel,headless=True);break
        except Exception:pass
    if browser is None:raise RuntimeError('Local Chrome or Edge is required to render SVGs')
    page=browser.new_page()
    for name in archive.namelist():
        filename=pathlib.PurePosixPath(name).stem
        if '/flags/4x3/' not in name or not name.endswith('.svg') or len(filename)!=2:continue
        svg=archive.read(name)
        data=page.evaluate('''async svg => { const image=new Image(); image.src='data:image/svg+xml;base64,'+svg; await image.decode(); const canvas=document.createElement('canvas'); canvas.width=160;canvas.height=120;canvas.getContext('2d').drawImage(image,0,0,160,120);return canvas.toDataURL('image/png').split(',')[1]; }''',base64.b64encode(svg).decode())
        png=base64.b64decode(data);(output/f'flag_{filename}.png').write_bytes(png)
        records.append({'iso':filename.upper(),'svgSha256':hashlib.sha256(svg).hexdigest(),'pngSha256':hashlib.sha256(png).hexdigest()})
    license_name=next(n for n in archive.namelist() if n.endswith('/LICENSE'))
    (root/'app/src/main/assets/licenses/flag-icons-MIT.txt').write_bytes(archive.read(license_name))
    browser.close()
(root/'assets/flags-source.json').write_text(json.dumps({'source':url,'commit':commit,'archiveSha256':hashlib.sha256(raw).hexdigest(),'license':'MIT','size':[160,120],'flags':sorted(records,key=lambda r:r['iso'])},indent=2)+'\n',encoding='utf-8')
mapping='\n'.join(f'        "{r["iso"]}" -> com.signet.client.R.drawable.flag_{r["iso"].lower()}' for r in sorted(records,key=lambda r:r['iso']))
(root/'app/src/main/java/com/signet/client/ui/FlagResources.kt').write_text('package com.signet.client.ui\n\n// Generated by scripts/fetch-flags.py; static references survive resource shrinking.\ninternal object FlagResources {\n    fun id(iso:String?):Int=when(iso){\n'+mapping+'\n        else -> 0\n    }\n}\n',encoding='utf-8')
print('Rendered',len(records),'local country flags; total bytes',sum(p.stat().st_size for p in output.glob('flag_*.png')))
